#!/usr/bin/env bash
# session-start.sh — the plugin's ONE SessionStart entry (#296).
#
# Claude Code runs every hook registered under one matcher IN PARALLEL, with
# no ordering guarantee (hooks reference, verified 2026-09-18). Two entries
# therefore meant two lines in whichever order won the race — and any plan
# for "one consolidated line" across them was impossible by construction.
# One entry, two scripts in a fixed order, is the honest version.
#
# Order: CLI-version observe/sync first (it may print the install-health
# warning), then the tenant-clone freshness gate. Each script still owns its
# own silence — a healthy session prints nothing from either.
#
# Cost of the order, stated: the two used to run in parallel under 30s/25s;
# they now run in series under one budget, and the network-bound freshness
# fetch is the one that gets cut if the budget blows. Inside a tenant the
# first script is sub-second (observe, then defer), so the common case is
# fine; outside a tenant it may fetch and install first.
#
# SessionStart hooks receive JSON on stdin. Read it once here; only the
# session registrar (#394) needs it, so the others get /dev/null.
# Neither child may fail session start: `|| true` and a final exit 0. The
# syntax of every child script is gated by tests/test_session_start_hooks.py
# (`bash -n`), because `|| true` would otherwise hide a broken child forever.

set -u

payload="$(cat 2>/dev/null || true)"

here="$(cd "$(dirname "$0")" && pwd)"

# ── Collect, then emit once (#402) ────────────────────────────────────
# Plain stdout from a SessionStart hook reaches CLAUDE only; the person never
# sees it. The skills hint (#395) exists for the person, so it travels as the
# JSON `systemMessage` ("shown to the user"), while everything the chain used
# to print plainly travels as `hookSpecificOutput.additionalContext` ("added
# to Claude's context") — https://code.claude.com/docs/en/hooks, JSON output
# + SessionStart decision control, read 2026-10-30.
#
# JSON is all-or-nothing: stdout counts as JSON only when it is ONE object
# with nothing but whitespace around it, and stdout that fails to parse is
# NOT added to Claude's context. So every child's stdout is captured (stderr
# still passes through untouched), and exactly one thing is printed at the
# end: the JSON object, or — with no hint (outside a tenant, no `cxp`, a
# `cxp` too old for `skills`) or any failure to build the JSON — the same
# plain text the chain printed before #402, in the same order.

# Order: CLI version, tenant freshness, then the session registrar (#394),
# which prints one line only when other sessions are active. (No comments
# inside the substitution: macOS bash 3.2 misparses an apostrophe there.)
ctx="$(
    bash "$here/sync-cli-version.sh" </dev/null || true
    bash "$here/tenant-freshness.sh" </dev/null || true
    printf '%s' "$payload" | bash "$here/session-register.sh" || true
)"
# Fourth, and last: the one-line skills hint (#395), generated by
# `cxp skills --hint`. The child already trims to one line; trim again here
# so a change there cannot turn the visible message into a paragraph.
hint="$(bash "$here/skills-hint.sh" </dev/null | head -n 1 || true)"

_plain() {
    [ -n "$ctx" ] && printf '%s\n' "$ctx"
    [ -n "$hint" ] && printf '%s\n' "$hint"
    return 0
}

if [ -z "$hint" ]; then
    _plain
    exit 0
fi

# python3 (on every Mac; -I so a stray json.py in the tenant cannot be
# imported) does the encoding, so no hand-rolled escaping can
# produce a parse failure. The hint stays in additionalContext too: before
# #402 Claude saw it, and systemMessage is not documented as reaching Claude.
json="$(CP_CTX="$ctx" CP_HINT="$hint" python3 -I -c '
import json, os
ctx, hint = os.environ["CP_CTX"], os.environ["CP_HINT"]
print(json.dumps({
    "systemMessage": hint,
    "hookSpecificOutput": {
        "hookEventName": "SessionStart",
        "additionalContext": "\n".join(p for p in (ctx, hint) if p),
    },
}))
' 2>/dev/null)" || json=""

case "$json" in
    "{"*"}") printf '%s\n' "$json" ;;
    *) _plain ;;
esac

exit 0
