"""The `cp` CLI — entry point for tenant operations.

Subcommands per spec v02 §2.1:
  cp init     → walk through populating .cp-engine.local.toml
  cp sync     → run one sync cycle locally (same logic as the Action)
  cp render   → re-render generated files (master-cp.md, CLAUDE.md)
  cp status   → show what would change without writing
"""

from __future__ import annotations

import sys
from datetime import datetime
from pathlib import Path

import click

from cp_engine.config import ConfigError, load
from cp_engine.config import CommittedConfigMissing
from cp_engine.init import InitAborted, run_init
from cp_engine.sync import SyncError, sync_tenant


@click.group()
@click.version_option(package_name="cp-engine")
def main() -> None:
    """Context Protocol Engine — tenant operations."""


@main.command()
@click.option(
    "--non-interactive",
    is_flag=True,
    help="Don't prompt; mark every committed project as skipped (useful in CI).",
)
def init(non_interactive: bool) -> None:
    """Walk through populating .cp-engine.local.toml interactively."""
    try:
        run_init(Path.cwd(), interactive=not non_interactive)
    except CommittedConfigMissing as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(2)
    except InitAborted as exc:
        click.echo(str(exc), err=True)
        sys.exit(1)
    except KeyboardInterrupt:
        click.echo("\nAborted. Partial progress (if any) has been saved.", err=True)
        sys.exit(130)


@main.command()
def sync() -> None:
    """Run one sync cycle for the current tenant."""
    try:
        config = load(Path.cwd())
    except ConfigError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(2)

    try:
        result = sync_tenant(config)
    except SyncError as exc:
        click.echo(f"Sync failed: {exc}", err=True)
        sys.exit(1)

    if result.no_op:
        click.echo(f"No changes ({result.projects_seen} projects checked).")
        return

    click.echo(f"Synced {result.projects_seen} projects.")
    for path in result.files_written:
        click.echo(f"  wrote    {path.relative_to(config.root)}")
    for path in result.files_deactivated:
        click.echo(f"  deactivated {path.relative_to(config.root)}")


@main.command()
def render() -> None:
    """Re-render generated files (alias for `cp sync` in v0.1)."""
    # In v0.1 there's no separate render-only path — sync already writes
    # only when content changed and never reaches out to the database
    # for unchanged regions. Future: a true `--no-network` render that
    # uses cached project state.
    click.echo("`cp render` is currently an alias for `cp sync`. Running sync…")
    ctx = click.get_current_context()
    ctx.invoke(sync)


@main.command(name="refresh-pristine")
@click.option(
    "--dry-run",
    is_flag=True,
    help="Show what would be refreshed without writing.",
)
def refresh_pristine(dry_run: bool) -> None:
    """Re-scaffold project CPs that have no hand-written content.

    A project CP is "pristine" if it still contains the placeholder text
    that the scaffold inserted ("<one-line description of what this
    project is and who it's for>"). Pristine CPs were generated by an
    older engine version and have outdated provenance, missing
    metadata blocks, or wrong section structures (e.g. v0.1 templates
    didn't have project-facts; v0.2 templates do).

    Edited CPs (the placeholder is gone or any other section was filled
    in) are NEVER touched — that's hand-written content the engine has
    no business overwriting.

    Use this once after upgrading cp-engine versions to refresh the
    template shape across the tenant.
    """
    try:
        config = load(Path.cwd())
    except ConfigError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(2)

    from cp_engine.refresh import refresh_pristine_cps

    try:
        result = refresh_pristine_cps(config, dry_run=dry_run)
    except SyncError as exc:
        click.echo(f"Refresh failed: {exc}", err=True)
        sys.exit(1)

    if not result.pristine_files:
        click.echo("No pristine project CPs found. Nothing to refresh.")
        return

    if dry_run:
        click.echo(f"Would refresh {len(result.pristine_files)} pristine project CP(s):")
    else:
        click.echo(f"Refreshed {len(result.pristine_files)} pristine project CP(s):")
    for path in result.pristine_files:
        click.echo(f"  {path.relative_to(config.root)}")
    if result.skipped_files:
        click.echo(f"\nSkipped {len(result.skipped_files)} edited CP(s) (hand-written content preserved).")


@main.command(name="migrate-to-v03")
@click.option(
    "--dry-run",
    is_flag=True,
    help="Show what would move without touching the disk.",
)
def migrate_to_v03(dry_run: bool) -> None:
    """One-shot move of v0.2's flat `projects/<code>.md` layout to v0.3's
    per-project working dirs at `<scope>/projects/<code>/cp.md`.

    Uses `git mv` to preserve rename detection. Refuses to run on a dirty
    working tree — commit or stash first. After this runs cleanly, regular
    `cp sync` keeps using the new layout."""
    try:
        config = load(Path.cwd())
    except ConfigError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(2)

    from cp_engine.migrate import MigrationError, migrate_to_v03 as _run

    try:
        result = _run(config, dry_run=dry_run)
    except MigrationError as exc:
        click.echo(f"Migration aborted: {exc}", err=True)
        sys.exit(1)
    except SyncError as exc:
        click.echo(f"Migration aborted: {exc}", err=True)
        sys.exit(1)

    label = "Would move" if dry_run else "Moved"
    if not result.moved and not result.skipped:
        click.echo("Nothing to migrate — no v0.2 layout files found.")
        return

    click.echo(f"{label} {len(result.moved)} file(s):")
    for src, dst in result.moved:
        click.echo(f"  {src.relative_to(config.root)} → {dst.relative_to(config.root)}")
    if result.skipped:
        click.echo(f"\nSkipped {len(result.skipped)} file(s) — resolve by hand:")
        for src, reason in result.skipped:
            click.echo(f"  {src.relative_to(config.root)}: {reason}")

    if not dry_run:
        click.echo(
            "\nReview the changes, then commit:\n"
            "  git status\n"
            '  git commit -m "cp-engine v0.3: restructure to per-project working directories"'
        )


@main.command(name="capture-session")
@click.option(
    "--source-repo",
    type=click.Path(exists=True, file_okay=False, path_type=Path),
    help="Source repo path (a code repo with a .cp-link). Mutually exclusive with --working-dir.",
)
@click.option(
    "--working-dir",
    "working_dir",
    type=click.Path(exists=True, file_okay=False, path_type=Path),
    help=(
        "cp working-dir path (for content-only projects with no separate "
        "source repo). Mutually exclusive with --source-repo. The cp tenant "
        "root is found by walking up for .cp-engine.toml, so --cp-tenant "
        "isn't needed."
    ),
)
@click.option(
    "--summary-file",
    "summary_file",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    required=True,
    help="Path to a file containing the session summary (Claude writes this).",
)
@click.option(
    "--user",
    required=True,
    help="Display name for the session author (e.g. \"Drew\").",
)
@click.option(
    "--cp-tenant",
    type=click.Path(exists=True, file_okay=False, path_type=Path),
    help="Path to the cp tenant clone. Required for unlinked source repos.",
)
@click.option("--no-commit", is_flag=True, help="Don't run git add/commit/push.")
@click.option("--no-push", is_flag=True, help="Commit but don't push.")
def capture_session_cmd(
    source_repo: Path | None,
    working_dir: Path | None,
    summary_file: Path,
    user: str,
    cp_tenant: Path | None,
    no_commit: bool,
    no_push: bool,
) -> None:
    """Write a session summary back to the cp tree.

    Two modes:

    \b
    --source-repo <path>  (default: cwd)
        For source-code repos with a .cp-link. Resolves destination via
        the link (self-healing if stale), or falls back to
        <cp-tenant>/exceptions/ for untracked repos.

    --working-dir <path>
        For content-only projects (1P engagements without a code repo).
        Skips source-repo resolution; writes directly to <path>/sessions/.
        The cp tenant root is found by walking up for .cp-engine.toml.

    Both modes write `<wd>/sessions/<YYYY-MM-DD>-<HHMM>-<user>.md`,
    update the project's `cp.md` Last session line, and commit + push.
    """
    from cp_engine.capture_session import (
        CaptureSessionError,
        capture_session,
        capture_session_in_working_dir,
    )

    if source_repo is not None and working_dir is not None:
        click.echo(
            "Error: pass --source-repo or --working-dir, not both.", err=True
        )
        sys.exit(2)

    summary_text = summary_file.read_text(encoding="utf-8")

    try:
        if working_dir is not None:
            result = capture_session_in_working_dir(
                working_dir=working_dir,
                summary_text=summary_text,
                user=user,
                commit=not no_commit,
                push=not (no_commit or no_push),
            )
        else:
            repo = (source_repo or Path.cwd()).resolve()
            result = capture_session(
                source_repo=repo,
                summary_text=summary_text,
                user=user,
                cp_tenant=cp_tenant,
                commit=not no_commit,
                push=not (no_commit or no_push),
            )
    except CaptureSessionError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(1)

    if result.is_exception:
        click.echo(
            f"Logged exception (repo not tracked in this cp tenant): "
            f"{result.summary_path}"
        )
    else:
        click.echo(f"Wrote session summary: {result.summary_path}")
        if result.cp_md_updated:
            click.echo("Updated cp.md Last session line.")
        if result.extra_files_committed:
            click.echo(
                f"Also committed {len(result.extra_files_committed)} other file(s) "
                f"in the working dir (binaries excluded by .gitignore):"
            )
            wd = result.cp_working_dir
            for p in result.extra_files_committed:
                rel = p.relative_to(wd) if wd else p
                click.echo(f"  {rel}")
    if result.commit_sha:
        # Distinguish actually-skipped (--no-push or --no-commit) from
        # actually-pushed from rebased-then-pushed. Push *failures* now
        # raise PushFailed and are surfaced via the CaptureSessionError
        # branch above, so reaching here with pushed=False means the
        # caller asked us not to push.
        if result.push_rebased:
            click.echo(
                f"Committed {result.commit_sha}, rebased on top of upstream, "
                "and pushed."
            )
        elif result.pushed:
            click.echo(f"Committed {result.commit_sha} and pushed.")
        else:
            click.echo(f"Committed {result.commit_sha} (push skipped).")


@main.command(name="project-context")
@click.option(
    "--working-dir",
    type=click.Path(exists=True, file_okay=False, path_type=Path),
    help="cp working dir. Defaults to cwd.",
)
@click.option("--user", help="Which `[local-repos.<user>]` entry to use.")
@click.option("--days", type=int, default=7, help="Lookback window. Default 7.")
def project_context_cmd(
    working_dir: Path | None,
    user: str | None,
    days: int,
) -> None:
    """Print recent activity for a project: git log + session captures.

    Run from inside a cp working dir. Reads the linked source repo's
    local clone path from `<tenant>/.cp-engine.toml [local-repos.<user>]`,
    runs `git log --since=<days> ago` there, lists session files in the
    working dir's `sessions/` directory from the same window, and prints
    one chronological timeline.
    """
    from cp_engine.project_context import ProjectContextError, project_context

    wd = (working_dir or Path.cwd()).resolve()
    try:
        result = project_context(working_dir=wd, user=user, days=days)
    except ProjectContextError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(1)

    click.echo(f"# {result.repo_name} — last {result.window_days} days")
    if result.github_url:
        click.echo(f"GitHub: {result.github_url}")
    click.echo(f"Local clone: {result.local_clone or '(not on this machine)'}")
    click.echo()

    if not result.commits and not result.sessions:
        click.echo("(no activity in window)")
        return

    # Merge commits + sessions on one timeline. Each entry has a `.when`
    # attribute; sort newest first.
    timeline: list[tuple[datetime, str]] = []
    for c in result.commits:
        line = (
            f"  {c.when.strftime('%Y-%m-%d %H:%M')}  commit {c.sha}  "
            f"({c.author}) {c.subject}"
        )
        timeline.append((c.when, line))
    for s in result.sessions:
        one = s.one_liner or "(no summary)"
        line = (
            f"  {s.when.strftime('%Y-%m-%d %H:%M')}  session         "
            f"({s.user}) {one}"
        )
        timeline.append((s.when, line))
    timeline.sort(key=lambda t: t[0], reverse=True)
    for _when, line in timeline:
        click.echo(line)
    click.echo()
    click.echo(f"({len(result.commits)} commits, {len(result.sessions)} sessions)")


@main.command(name="link-local")
def link_local_cmd() -> None:
    """Wire `.cp-link` files into each source repo named in `[local-repos]`.

    Reads `.cp-engine.local.toml`'s `[local-repos]` table, validates each
    path is a git repo whose remote matches the entry, finds the
    corresponding cp working dir by walking the cp tenant tree, and writes
    `<source-repo>/.cp-link` containing the absolute path of that working
    dir. Also adds `.cp-link` to `.git/info/exclude` so the source repo
    won't accidentally commit it.

    Idempotent — re-running with no changes is a no-op.
    """
    try:
        config = load(Path.cwd())
    except ConfigError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(2)

    from cp_engine.link_local import LinkLocalError, link_local as _run

    if not config.local_repos:
        click.echo(
            "No [local-repos] entries in .cp-engine.local.toml. Add one per "
            "repo you want linked, e.g.:\n\n"
            "  [local-repos]\n"
            '  "mc-2"      = "/Users/you/Documents/Python/mc-2"\n'
            '  "cp-engine" = "/Users/you/Documents/Python/context-protocol"\n'
        )
        return

    try:
        results = _run(config)
    except LinkLocalError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(1)

    wrote = sum(1 for r in results if r.wrote_link)
    excluded = sum(1 for r in results if r.excluded)
    for r in results:
        action = "wrote" if r.wrote_link else "ok   "
        click.echo(f"  {action} {r.source_repo_path}/.cp-link → {r.cp_working_dir}")
    click.echo(
        f"\n{len(results)} repo(s) linked. "
        f"{wrote} new/updated link file(s); "
        f"{excluded} .git/info/exclude update(s)."
    )


