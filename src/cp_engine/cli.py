@main.command("fathom-auto-poll")
@click.option(
    "--limit",
    type=int,
    default=20,
    help="Max meetings to consider per poll. Default 20.",
)
@click.option(
    "--dry-run",
    is_flag=True,
    help="List what would be staged + classified, but don't write files.",
)
def fathom_auto_poll_cmd(limit: int, dry_run: bool) -> None:
    """Poll Fathom Supabase for new meetings and stage them.

    Confidence gate: meetings with non-empty + non-`untagged` `project_tags`
    are staged to `transcripts/incoming/` for /cp-ingest. Meetings with no
    real tags go to `transcripts/needs-review/` for manual handling.

    State (last_polled_at + processed_ids) at `.cp-engine/state.json`
    (gitignored). Idempotent — already-processed ids are skipped.

    Output: JSON summary `{polled, staged_for_ingest[], staged_for_review[],
    skipped_already_processed[], errors[]}`.

    The `[fathom-ingest]` GitHub Actions workflow runs this on a cron and
    commits the staged files (not the deepening — /cp-ingest still requires
    /cp-ingest plugin orchestration which has Claude as the planner).
    """
    import json
    from cp_engine.fathom import (
        list_meetings,
        fetch_meeting,
        stage_transcript,
        has_good_tags,
        load_state,
        save_state,
        already_processed,
        mark_processed,
    )

    config = _load_config_or_die()
    state = load_state(config.root)
    meetings = list_meetings(config, since_iso=state.last_polled_at, limit=limit)

    summary: dict = {
        "polled": len(meetings),
        "staged_for_ingest": [],
        "staged_for_review": [],
        "skipped_already_processed": [],
        "errors": [],
    }

    for m in meetings:
        if already_processed(state, m.id):
            summary["skipped_already_processed"].append(m.id)
            continue
        try:
            target = "ingest" if has_good_tags(m.project_tags) else "review"
            if dry_run:
                bucket = "staged_for_ingest" if target == "ingest" else "staged_for_review"
                summary[bucket].append({"id": m.id, "title": m.title, "tags": m.project_tags})
                continue
            full = fetch_meeting(config, m.id)
            path = stage_transcript(
                full,
                tenant_root=config.root,
                needs_review=(target == "review"),
            )
            bucket = "staged_for_ingest" if target == "ingest" else "staged_for_review"
            summary[bucket].append(
                {"id": m.id, "title": m.title, "path": str(path), "tags": m.project_tags}
            )
            state = mark_processed(state, m.id)
        except Exception as exc:
            summary["errors"].append({"id": m.id, "error": str(exc)})

    if not dry_run:
        save_state(state, config.root)

    click.echo(json.dumps(summary, indent=2))


@main.command("prep-agenda")
@click.option(
    "--projects",
    "project_filter",
    default="",
    help="Comma-separated project codes to scope the agenda to. "
    "Empty (default) → full sprint planning across all active projects.",
)
@click.option(
    "--out",
    type=click.Path(dir_okay=False, path_type=Path),
    default=None,
    help="Write the agenda to this file path. Defaults to stdout.",
)
@click.option(
    "--summary",
    is_flag=True,
    help="Emit JSON metrics (workload by owner, coverage, urgency counts) "
    "instead of the rendered markdown. The /cp-prep plugin uses this.",
)
@click.option(
    "--no-sync",
    is_flag=True,
    help="Skip the automatic sync-if-stale check at the start. "
    "By default, prep-agenda auto-runs `cp sync` if master-cp's last sync "
    "is more than 10 minutes old, so the agenda never shows stale data.",
)
def prep_agenda_cmd(
    project_filter: str, out: Path | None, summary: bool, no_sync: bool
) -> None:
    """Render a sprint-planning agenda from current cp tenant state.

    Reads master-cp's project list, weekly-cp.md decisions, current-week
    sprint files, and per-project cp.md Quick Resume sections; cross-
    references everything into project-grouped blocks.

    Default: agenda for all active projects (full sprint planning).
    With `--projects <code>,<code>...`: scoped agenda for those projects only.

    Output is markdown. Default to stdout; pass `--out sprints/<W##>/_agenda.md`
    to overwrite the per-week agenda file. Pass `--summary` to emit JSON
    metrics instead (used by the /cp-prep plugin command).
    """
    import json
    from datetime import datetime, timedelta
    from cp_engine.agenda import build_agenda, build_agenda_summary, is_sync_stale
    from cp_engine.sync import _default_backend_factory, sync_tenant

    config = _load_config_or_die()

    # v0.8.8.2: auto-sync if stale. Avoids the "agenda shows yesterday's
    # owner data" footgun. Opt-out via --no-sync for environments where
    # the network round-trip isn't acceptable (CI dry-runs, etc.).
    if not no_sync and is_sync_stale(config):
        click.echo("master-cp sync is stale; running cp sync first…", err=True)
        try:
            sync_tenant(config)
        except Exception as exc:
            click.echo(f"sync failed (continuing with stale data): {exc}", err=True)

    backend = _default_backend_factory(config.sync.backend)
    projects = backend.read_projects(config)

    # Pull last-week allocations the same way master-cp does, so the agenda's
    # per-project "last sprint hours" line matches what's in master-cp.md.
    today = datetime.now().date()
    last_monday = today - timedelta(days=today.weekday() + 7)
    try:
        allocations = backend.read_allocations(config, last_monday.isoformat())
    except Exception:
        allocations = None

    last_sprint_hours_by_project: dict[str, str] = {}
    if allocations and getattr(allocations, "by_project", None):
        for code, alloc in allocations.by_project.items():
            entries = [f"{e.person_name.split()[0]} {e.hours:g}h" for e in alloc.entries]
            if entries:
                last_sprint_hours_by_project[code] = ", ".join(entries)

    code_filter = tuple(c.strip() for c in project_filter.split(",") if c.strip()) or None

    if summary:
        s = build_agenda_summary(
            config,
            tuple(projects),
            today=today,
            project_filter=code_filter,
            last_sprint_hours_by_project=last_sprint_hours_by_project,
        )
        click.echo(json.dumps(s.to_dict(), indent=2))
        return

    agenda_md = build_agenda(
        config,
        tuple(projects),
        today=today,
        project_filter=code_filter,
        last_sprint_hours_by_project=last_sprint_hours_by_project,
    )

    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(agenda_md)
        click.echo(f"wrote {out}")
    else:
        click.echo(agenda_md)


def _load_config_or_die() -> "TenantConfig":  # noqa: F821
    """Load tenant config from cwd; exit with a friendly error on failure."""
    try:
        return load(Path.cwd())
    except CommittedConfigMissing:
        click.echo(
            "No .cp-engine.toml in this directory. Run `cp init` "
            "or cd into the cp tenant root.",
            err=True,
        )
        sys.exit(1)
    except ConfigError as exc:
        click.echo(f"Config error: {exc}", err=True)
        sys.exit(1)


