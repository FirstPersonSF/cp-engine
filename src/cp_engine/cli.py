@main.command("list-active-projects")
@click.option(
    "--scope",
    type=click.Choice(["1p", "fpsf", "canonic", "all"]),
    default="all",
    help="Filter by scope. Default 'all'.",
)
@click.option(
    "--company",
    default=None,
    help="Filter by company code (case-insensitive, e.g. 'GGL' or 'IBX'). "
    "Used by /cp-ingest --account <company> to find the projects a "
    "multi-project account meeting touches. Default: all companies.",
)
def list_active_projects_cmd(scope: str, company: str | None) -> None:
    """List active projects from MC-2 as JSON for transcript classification.

    Output: list of {code, name, company_code, company_name, owner, scope}.
    Used by /cp-ingest plugin to give Claude the candidate-projects list
    when classifying which projects a transcript touches.
    """
    import json
    from cp_engine.state import scope_for
    from cp_engine.status import is_active_status
    from cp_engine.sync import _default_backend_factory

    config = _load_config_or_die()
    backend = _default_backend_factory(config.sync.backend)
    projects = backend.read_projects(config)

    company_lc = company.lower() if company else None

    out = []
    for p in projects:
        if p.source == "engagement":
            if not is_active_status(p.status) or p.is_internal:
                continue
        else:
            if p.status != "Active":
                continue
        proj_scope = scope_for(p.company_kind)
        if scope != "all" and proj_scope != scope:
            continue
        # Phase B.2: --company filter for /cp-ingest --account flow.
        if company_lc and (p.company_code or "").lower() != company_lc:
            continue
        out.append(
            {
                "code": p.code,
                "name": p.name,
                "company_code": p.company_code,
                "company_name": p.company_name,
                "owner": p.owner,
                "scope": proj_scope,
                "source": p.source,
            }
        )
    out.sort(key=lambda r: (r["scope"], r["code"]))
    click.echo(json.dumps(out, indent=2))


def _load_spine_elements(config, code: str):
    """Load a project's spine elements (MC-2 canonical, disk fallback).

    Returns ``(elements, project_dir)`` where ``project_dir`` is the resolved
    working dir if the disk path was used, else ``None`` (MC-2 served the read).
    Exits 1 via ``SpineDirNotFound`` if the project can't be resolved on disk
    during fallback. Shared by ``cp spine`` and ``cp sweep``.
    """
    from cp_engine.spine import (
        SpineDirNotFound,
        find_spine_dir,
        load_spine,
        load_spine_from_mc2,
    )
    from cp_engine.sync import BackendUnavailable
    from cp_engine.sync_mc2 import MC2Backend

    elements: tuple = ()
    project_dir = None
    reached_mc2 = False
    served_by_mc2 = False  # connected AND query succeeded — MC-2 is the truth source

    backend = MC2Backend()
    try:
        client = backend.connect(config)  # lightweight: client only, no read
        reached_mc2 = True
    except BackendUnavailable as exc:
        click.echo(f"(MC-2 unavailable: {exc})", err=True)
    except Exception as exc:  # noqa: BLE001 — unexpected connect failure, still degrade
        click.echo(f"(WARNING: MC-2 connect failed unexpectedly: {exc})", err=True)

    if reached_mc2:
        try:
            elements = load_spine_from_mc2(client, code)
            served_by_mc2 = True  # an empty result is still the authoritative answer
        except Exception as exc:  # noqa: BLE001 — connected but query failed = likely a bug
            click.echo(
                f"(WARNING: MC-2 spine read failed — this may be a schema/query bug: {exc})",
                err=True,
            )

    # Reads treat MC-2 as the source of truth. We only touch disk when MC-2 did
    # not serve the read — and when we do, we say so loudly: the result is
    # last-known, unverified state, NOT the authoritative spine.
    if not served_by_mc2:
        click.echo(
            "(MC-2 unreachable — showing last-known markdown-derived state, "
            "unverified.)",
            err=True,
        )
        try:
            project_dir = find_spine_dir(config.root, code)
        except SpineDirNotFound as exc:
            click.echo(str(exc), err=True)
            sys.exit(1)
        elements = load_spine(project_dir)
    elif not elements:
        # MC-2 served the read but the project has no spine elements yet — say
        # so, so an empty render isn't mistaken for a failed/unreachable read.
        click.echo(f"(MC-2 returned 0 spine elements for {code}.)", err=True)

    return elements, project_dir


def _spine_mc2_client(config):
    """Connect to MC-2 for best-effort read-only facets, or return None.

    Used by `cp spine`'s Source-documents facet, which needs a live client that
    `_load_spine_elements` does not expose. Never raises — a facet must never
    break the sweep — so any connect failure degrades to None (facet omitted).
    """
    from cp_engine.sync_mc2 import MC2Backend

    try:
        return MC2Backend().connect(config)
    except Exception:  # noqa: BLE001 — facet is best-effort; degrade silently
        return None


